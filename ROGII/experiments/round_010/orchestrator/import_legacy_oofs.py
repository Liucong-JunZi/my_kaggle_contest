"""Import pre-existing OOFs (Phase 14B, Phase 5, etc.) into the candidate pool.

These weren't generated by candidates/cXX_*.py but they're still valid
candidates — same fold map (verified), same target convention. We mint
candidate_ids and write them through the standard oof_writer to inherit
schema validation + metric computation.

Existing OOFs imported:
    p14_lgb            from oof_phase14.lgb_oof
    p14_cat            from oof_phase14.cat_oof
    p14_pf_ancc        from oof_phase14.pf_ancc - last_known_tvt
    p14_pf_ens12       from oof_phase14.pf_ens_s12 - last_known_tvt
    p11_lgb            from oof_phase11.lgb_oof_p11   (multi-PN + spatial)
    p11_cat            from oof_phase11.cat_oof_p11
    p5_lgb             from oof_phase5.lgb_oof
    p5_cat             from oof_phase5.cat_oof

These come into the pool with a special `source: "imported"` tag in metadata
(distinct from `candidate_type` which records the underlying algorithm).
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROUND_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROUND_DIR))

R8_DIR = Path("/Users/liucong/code/kaggle/ROGII/results/round_008")

from shared.data_loader import load_joined
from shared.oof_writer import write_oof


# (candidate_id, source_parquet, source_col, abs_or_offset, candidate_type, hparams, perwell_seed_label)
IMPORTS = [
    ("p14_lgb",       "oof_phase14.parquet", "lgb_oof",     "offset",
     "lightgbm", {"n_estimators":3000, "lr":0.02, "num_leaves":127}, 42),
    ("p14_cat",       "oof_phase14.parquet", "cat_oof",     "offset",
     "catboost", {"iterations":3000, "lr":0.05, "depth":8}, 42),
    ("p14_pf_ancc",   "oof_phase14.parquet", "pf_ancc",     "abs",
     "pf_single", {"seed":42, "init_spread":0.3}, 42),
    ("p14_pf_ens12",  "oof_phase14.parquet", "pf_ens_s12",  "abs",
     "pf_ensemble16", {"n_seeds":16, "scale":12, "init_spread":4.5}, 0),
    ("p11_lgb",       "oof_phase11.parquet", "lgb_oof_p11", "offset",
     "lightgbm_p11", {"feats":"v4 + multi-PN + spatial"}, 42),
    ("p11_cat",       "oof_phase11.parquet", "cat_oof_p11", "offset",
     "catboost_p11", {"feats":"v4 + multi-PN + spatial"}, 42),
    ("p5_lgb",        "oof_phase5.parquet",  "lgb_oof",     "offset",
     "lightgbm_p5", {"feats":"v4 36-feat"}, 42),
    ("p5_cat",        "oof_phase5.parquet",  "cat_oof",     "offset",
     "catboost_p5", {"feats":"v4 36-feat"}, 42),
]


def main():
    base = load_joined()[["well", "row_idx", "target", "last_known_tvt", "fold"]]
    base = base.reset_index(drop=True)
    print(f"Base joined: {len(base):,} rows / {base['well'].nunique()} wells")

    n_ok = 0
    for (cid, src, col, mode, ctype, hp, seed) in IMPORTS:
        try:
            d = pd.read_parquet(R8_DIR / src)
        except Exception as e:
            print(f"  ! {cid}: read fail {e}")
            continue
        # Inner-join on (well, row_idx) — must align with base
        m = base.merge(d[["well", "row_idx", col]], on=["well", "row_idx"], how="left")
        nan_count = m[col].isna().sum()
        if nan_count > 0:
            print(f"  ! {cid}: {nan_count} rows missing in source — skipping")
            continue

        if mode == "abs":
            oof = m[col].values - m["last_known_tvt"].values
        else:
            oof = m[col].values

        df_oof = pd.DataFrame({
            "well":     m["well"].values,
            "row_idx":  m["row_idx"].values.astype(np.int32),
            "fold":     m["fold"].values.astype(np.int8),
            "target":   m["target"].values.astype(np.float32),
            "oof_pred": oof.astype(np.float32),
        })

        out = write_oof(
            candidate_id   = cid,
            df_oof         = df_oof,
            candidate_type = ctype,
            features_used  = ["__imported_from_" + src + ":" + col],
            hyperparams    = hp,
            seed           = seed,
            train_time_sec = 0.0,
            extra_meta     = {"source": "imported", "source_parquet": src, "source_col": col},
        )
        print(f"  ✓ {cid}: {out.name}")
        n_ok += 1

    print(f"\nImported {n_ok}/{len(IMPORTS)} candidates")


if __name__ == "__main__":
    main()
