DATA_DIR   = "/Users/liucong/code/kaggle/ROGII/rogii-wellbore-geology-prediction/train"
CACHE_DIR  = Path("/Users/liucong/code/kaggle/ROGII/data/cache/cfg-img-medium")
CKPT       = CACHE_DIR / "best_model.pth"
OUT_DIR    = Path("/Users/liucong/code/kaggle/ROGII/results/round_007")
OUT_DIR.mkdir(parents=True, exist_ok=True)

COMPRESSION = 24    # cfg-img-medium target_step
H_H, H_F = 48, 528  # known/lateral columns


def sdf_inference():
    """Load model, run on val.h5, return dict: wid -> tvt_sdf[H], sdf_min[H]."""
    device = torch.device("mps" if torch.backends.mps.is_available() else "cpu")
    model = GeoSteerNet(in_channels=3, backbone_name="nvidia/mit-b0").to(device)
    model.load_state_dict(torch.load(CKPT, map_location=device))
    model.eval()

    with h5py.File(CACHE_DIR / "val.h5", "r") as f:
        X = f["X"][:]
        well_ids = [s.decode() for s in f["well_ids"][:]]
        t_tvt = f["t_tvt"][:]
        mask = f["mask"][:]

    out = {}
    with torch.no_grad():
        for i in range(0, len(X), 2):
            batch = torch.from_numpy(X[i:i+2]).float().to(device)
            hist = batch[:, 2:3]
            sdf = model(batch, hist).cpu().numpy()
            for k in range(sdf.shape[0]):
                idx = i + k
                sdf_abs = np.abs(sdf[k, 0])
                t_idx = sdf_abs.argmin(axis=0)
                tvt_pred = t_tvt[idx][t_idx]
                sdf_min = sdf_abs.min(axis=0)
                out[well_ids[idx]] = {
                    "tvt_sdf": tvt_pred.astype(np.float32),    # (H,)
                    "sdf_min": sdf_min.astype(np.float32),     # (H,)
                    "mask": mask[idx].astype(np.float32),
                }
    return out, well_ids


def build_features(sdf_out, well_ids):
    """For each well, build per-lateral-row features + target.

    The image was generated by gen_images: H=576 cols where first H_H=48 are
    known, rest H_F=528 are lateral. Image is compression=24 ft/col. We need
    to map back to the raw CSV's lateral rows.
    """
    rows = []

    for wid in well_ids:
        h = pd.read_csv(f"{DATA_DIR}/{wid}__horizontal_well.csv")
        tvt_inp = h["TVT_input"].values
        tvt = h["TVT"].values
        z = h["Z"].values
        x = h["X"].values
        y = h["Y"].values
        md = h["MD"].values
        gr_raw = h["GR"].values

        # Mask + GR clean
        gr_clean = pd.Series(gr_raw).interpolate(limit_direction="both").bfill().ffill().values
        gr_smooth = savgol_filter(gr_clean, 51, 2) if len(gr_clean) > 51 else gr_clean.copy()
        gr_std20 = pd.Series(gr_clean).rolling(20, center=True, min_periods=1).std().fillna(0).values

        # Lateral start
        mask_lat = np.isnan(tvt_inp)
        if mask_lat.sum() == 0:
            continue
        last_known_idx = np.flatnonzero(~mask_lat)[-1]
        last_known_tvt = float(tvt_inp[last_known_idx])
        last_known_z = float(z[last_known_idx])
        last_known_md = float(md[last_known_idx])
        last_known_gr = float(gr_smooth[last_known_idx])

        # Image-side prediction (already in TVT units, full H=576 cols at comp=24)
        tvt_sdf_img = sdf_out[wid]["tvt_sdf"]   # (576,)
        sdf_min_img = sdf_out[wid]["sdf_min"]   # (576,)

        # Lateral rows in raw CSV
        lat_idx = np.flatnonzero(mask_lat)
        for r in lat_idx:
            md_offset = float(md[r] - last_known_md)        # in feet
            # Map to image lateral column index: H_H + (md_offset / compression)
            img_col = int(H_H + round(md_offset / COMPRESSION))
            img_col = min(max(img_col, 0), 575)

            target = float(tvt[r] - last_known_tvt) if not np.isnan(tvt[r]) else np.nan
            if np.isnan(target):
                continue

            rows.append({
                "well": wid,
                "row_idx": int(r),
                # Geometry
                "md_offset": md_offset,
                "dz_from_last": float(z[r] - last_known_z),    # physics prior signal
                "z_rel": float(z[r]),
                "x_rel": float(x[r] - x[last_known_idx]),
                "y_rel": float(y[r] - y[last_known_idx]),
                # GR
                "gr": float(gr_clean[r]),
                "gr_smooth": float(gr_smooth[r]),
                "gr_std20": float(gr_std20[r]),
                "gr_diff_from_last": float(gr_smooth[r] - last_known_gr),
                # SegFormer image signals
                "tvt_sdf_rel": float(tvt_sdf_img[img_col] - last_known_tvt),
                "sdf_confidence": float(sdf_min_img[img_col]),  # lower = more confident
                # Static per-well
                "last_known_tvt": last_known_tvt,
                "last_known_z": last_known_z,
                # Target
                "target": target,
            })
    return pd.DataFrame(rows)


def physics_pred(df):
    """tvt_phys_offset = -dz_from_last (since dtvt ≈ -dz)."""
    return -df["dz_from_last"].values


def run_cv(df, feature_cols, label):
    gkf = GroupKFold(n_splits=5)
    oof = np.zeros(len(df))
    fold_rmses = []
    for fold, (tr_idx, va_idx) in enumerate(gkf.split(df, df["target"], groups=df["well"])):
        X_tr, X_va = df.iloc[tr_idx][feature_cols], df.iloc[va_idx][feature_cols]
        y_tr, y_va = df.iloc[tr_idx]["target"], df.iloc[va_idx]["target"]
        model = lgb.LGBMRegressor(
            n_estimators=2000, learning_rate=0.02, num_leaves=63,
            min_child_samples=20, reg_alpha=0.1, reg_lambda=0.1,
            verbose=-1,
        )
        model.fit(X_tr, y_tr, eval_set=[(X_va, y_va)],
                  callbacks=[lgb.early_stopping(50, verbose=False)])
        pred = model.predict(X_va)
        oof[va_idx] = pred
        fold_rmse = float(root_mean_squared_error(y_va, pred))
        fold_rmses.append(fold_rmse)
        print(f"  fold {fold+1}: {fold_rmse:.3f} | best_iter={model.best_iteration_}")
    overall = float(root_mean_squared_error(df["target"], oof))
    print(f"  [{label}] OOF RMSE: {overall:.3f} | fold mean: {np.mean(fold_rmses):.3f}")
    return oof, overall, fold_rmses


def per_well_rmse(df, oof, label):
    """Compute mean per-well RMSE (apples-to-apples with SegFormer 15.84)."""
    out = []
    for wid, g in df.groupby("well"):
        idx = g.index.values
        pred_abs = g["last_known_tvt"].values + oof[idx]
        true_abs = g["last_known_tvt"].values + g["target"].values
        rmse = float(np.sqrt(np.mean((pred_abs - true_abs) ** 2)))
        out.append((wid, rmse, len(g)))
    rmses = np.array([r[1] for r in out])
    print(f"  [{label}] per-well RMSE: mean={rmses.mean():.2f} median={np.median(rmses):.2f} max={rmses.max():.2f}")
    return rmses


def main():
    print("=== R7 Hybrid: SegFormer + LightGBM ===\n")
    print("[1/3] SegFormer inference on val.h5 (50 curated wells)...")
    t0 = time.time()
    sdf_out, well_ids = sdf_inference()
    print(f"      done in {time.time()-t0:.1f}s\n")

    print("[2/3] Building features...")
    t0 = time.time()
    df = build_features(sdf_out, well_ids)
    print(f"      done in {time.time()-t0:.1f}s | rows={len(df)} wells={df['well'].nunique()}\n")

    # Save features for reuse
    df.to_parquet(OUT_DIR / "features.parquet")

    # Baseline 0: physics only
    print("[3/3] Models:\n")
    phys_pred = physics_pred(df)
    phys_rmse = float(root_mean_squared_error(df["target"], phys_pred))
    print(f"  [physics: -dz] flat RMSE: {phys_rmse:.3f}")
    phys_perwell = per_well_rmse(df, phys_pred, "physics: -dz")

    # Baseline 1: SegFormer SDF only (raw, no anchor)
    sdf_pred = df["tvt_sdf_rel"].values
    sdf_rmse = float(root_mean_squared_error(df["target"], sdf_pred))
    print(f"\n  [SegFormer SDF raw] flat RMSE: {sdf_rmse:.3f}")
    sdf_perwell = per_well_rmse(df, sdf_pred, "SegFormer SDF raw")

    # Model A: LightGBM WITHOUT image features
    geo_cols = ["md_offset", "dz_from_last", "z_rel", "x_rel", "y_rel",
                "gr", "gr_smooth", "gr_std20", "gr_diff_from_last",
                "last_known_tvt", "last_known_z"]
    print(f"\n  [LightGBM geo+gr only ({len(geo_cols)} feats)]")
    oof_geo, geo_rmse, _ = run_cv(df, geo_cols, "geo+gr")
    geo_perwell = per_well_rmse(df, oof_geo, "geo+gr")

    # Model B: LightGBM WITH image features
    full_cols = geo_cols + ["tvt_sdf_rel", "sdf_confidence"]
    print(f"\n  [LightGBM geo+gr+SDF ({len(full_cols)} feats)] ⭐")
    oof_full, full_rmse, _ = run_cv(df, full_cols, "geo+gr+sdf")
    full_perwell = per_well_rmse(df, oof_full, "geo+gr+sdf")

    # Save metrics
    metrics = {
        "n_wells": df["well"].nunique(), "n_rows": len(df),
        "physics_flat_rmse": phys_rmse,
        "physics_perwell_mean": float(phys_perwell.mean()),
        "sdf_raw_flat_rmse": sdf_rmse,
        "sdf_raw_perwell_mean": float(sdf_perwell.mean()),
        "lgb_geo_flat_rmse": geo_rmse,
        "lgb_geo_perwell_mean": float(geo_perwell.mean()),
        "lgb_full_flat_rmse": full_rmse,
        "lgb_full_perwell_mean": float(full_perwell.mean()),
        "delta_sdf_to_lgb_full_perwell": float(sdf_perwell.mean() - full_perwell.mean()),
    }
    with open(OUT_DIR / "metrics.json", "w") as f:
        json.dump(metrics, f, indent=2)
    print(f"\n=== Summary (per-well mean RMSE, apples-to-apples) ===")
    print(f"  physics -dz         : {phys_perwell.mean():.2f}")
    print(f"  SegFormer SDF raw   : {sdf_perwell.mean():.2f}  (was 15.84 in train.log; differs due to no subpixel/no anchor here)")
    print(f"  LGB geo+gr          : {geo_perwell.mean():.2f}")
    print(f"  LGB geo+gr+SDF      : {full_perwell.mean():.2f}")
    print(f"  → metrics: {OUT_DIR}/metrics.json")


if __name__ == "__main__":
    main()
