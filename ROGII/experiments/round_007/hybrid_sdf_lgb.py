"""R7: Hybrid SegFormer + LightGBM.

Pipeline:
1. Load cfg-img-medium best ckpt + run inference on its val set (50 wells, never seen).
2. For each lateral row of each well: extract features from raw CSV + SDF inference.
3. Target = TVT_lateral - last_known_tvt (relative offset).
4. 5-fold GroupKFold LightGBM, group=well_id.
5. Final pred = last_known_tvt + LightGBM(features).
6. Per-well RMSE on lateral rows, compared to SegFormer alone (raw 15.84, anc 13.67).

Features per row:
- Geometry: X, Y, Z, dz, MD_offset_from_last_known
- GR raw + GR_smooth_51 + GR_std_20
- SegFormer signals: tvt_sdf_pred, sdf_min_value (confidence), tvt_sdf_minus_last_known
- Static per-well: last_known_tvt, well_compression_step
"""
